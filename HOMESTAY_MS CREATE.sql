// CREATE QUERY

-- CUSTOMER table
CREATE TABLE CUSTOMER (
    CUST_ID VARCHAR2(20) PRIMARY KEY,
    CUST_FNAME VARCHAR2(50) NOT NULL,
    CUST_LNAME VARCHAR2(50) NOT NULL,
    CUST_PHONE VARCHAR2(15)
);

-- SUPPLIER table
CREATE TABLE SUPPLIER (
    SUPP_ID VARCHAR2(20) PRIMARY KEY,
    SUPP_NAME VARCHAR2(100) NOT NULL,
    SUPP_PHONE VARCHAR2(15),
    SUPP_EMAIL VARCHAR2(100),
    SUPP_ADDRESS VARCHAR2(200)
);

-- HOMESTAY table
CREATE TABLE HOMESTAY (
    HOMESTAY_ID VARCHAR2(20) PRIMARY KEY,
    HOMESTAY_NAME VARCHAR2(100) NOT NULL,
    PRICE_RATE NUMBER(10,2) NOT NULL,
    DESCRIPTIONS VARCHAR2(500),
    STATUS VARCHAR2(20) DEFAULT 'AVAILABLE'
);

-- EMPLOYEE table
CREATE TABLE EMPLOYEE (
    EMP_ID VARCHAR2(20) PRIMARY KEY,
    EMP_FNAME VARCHAR2(50) NOT NULL,
    EMP_LNAME VARCHAR2(50) NOT NULL,
    EMP_DOB DATE,
    EMP_HIRE_DATE DATE NOT NULL,
    EMP_PHONE VARCHAR2(15),
    EMP_TYPE VARCHAR2(50) NOT NULL  
);

//FULL-TIME
CREATE TABLE FULL_TIME (
    EMP_ID VARCHAR2(20) PRIMARY KEY,
    MONTHLY_WAGE NUMBER(10,2) NOT NULL,
    CONSTRAINT FK_FULLTIME_EMP
        FOREIGN KEY (EMP_ID) REFERENCES EMPLOYEE(EMP_ID)
);

//PART-TIME
CREATE TABLE PART_TIME (
    EMP_ID VARCHAR2(20) PRIMARY KEY,
    HOURLY_WAGE NUMBER(10,2) NOT NULL,
    CONSTRAINT FK_PARTTIME_EMP
        FOREIGN KEY (EMP_ID) REFERENCES EMPLOYEE(EMP_ID)
);


-- ITEM table
CREATE TABLE ITEM (
    ITEM_NO VARCHAR2(20) PRIMARY KEY,
    SUPP_ID VARCHAR2(20),
    ITEM_NAME VARCHAR2(100) NOT NULL,
    ITEM_TYPE VARCHAR2(50),
    ITEM_DESC VARCHAR2(500),
    RATE_TYPE VARCHAR2(20),
    ITEM_RATE NUMBER(10,2) NOT NULL,
    ITEM_STATUS VARCHAR2(20),
    CONSTRAINT fk_item_supplier 
    FOREIGN KEY (SUPP_ID) REFERENCES SUPPLIER(SUPP_ID)
);

-- BOOKING table
CREATE TABLE BOOKING (
    BOOKING_ID VARCHAR2(20) PRIMARY KEY,
    CUST_ID VARCHAR2(20) NOT NULL,
    HOMESTAY_ID VARCHAR2(20) NOT NULL,
    BOOKING_DATE DATE DEFAULT SYSDATE,
    CHECKIN DATE NOT NULL,
    CHECKOUT DATE NOT NULL,
    TOTAL_NIGHT NUMBER,
    CONSTRAINT fk_booking_customer 
    FOREIGN KEY (CUST_ID) REFERENCES CUSTOMER(CUST_ID),
    CONSTRAINT fk_booking_homestay 
    FOREIGN KEY (HOMESTAY_ID) REFERENCES HOMESTAY(HOMESTAY_ID)
);

-- PAYMENT table
CREATE TABLE PAYMENT (
    PAY_ID VARCHAR2(20) PRIMARY KEY,
    EMP_ID VARCHAR2(20),
    BOOKING_ID VARCHAR2(20) NOT NULL,
    TOTAL_PRICE NUMBER(10,2) NOT NULL,
    PAY_STATUS VARCHAR2(20) DEFAULT 'PENDING',
    PAYMENT_DATE DATE,
    PAYMENT_METHOD VARCHAR2(20),
    CONSTRAINT fk_payment_employee 
    FOREIGN KEY (EMP_ID) REFERENCES EMPLOYEE(EMP_ID),
    CONSTRAINT fk_payment_booking 
    FOREIGN KEY (BOOKING_ID) REFERENCES BOOKING(BOOKING_ID)
);

-- RECEIPT table
CREATE TABLE RECEIPT (
    RECEIPT_NO VARCHAR2(20) PRIMARY KEY,
    PAY_ID VARCHAR2(20) NOT NULL,
    RECEIPT_DATE DATE DEFAULT SYSDATE,
    CONSTRAINT fk_receipt_payment 
    FOREIGN KEY (PAY_ID) REFERENCES PAYMENT(PAY_ID)
);

-- BOOKINGITEM table (junction table for booking and item)
CREATE TABLE BOOKINGITEM (
    BOOKING_ID VARCHAR2(20) NOT NULL,
    ITEM_NO VARCHAR2(20) NOT NULL,
    SUBTOTAL NUMBER(10,2) NOT NULL,
    USAGE_QUANTITY NUMBER NOT NULL,
    PRIMARY KEY (BOOKING_ID, ITEM_NO),
    CONSTRAINT fk_bookingitem_booking 
    FOREIGN KEY (BOOKING_ID) REFERENCES BOOKING(BOOKING_ID),
    CONSTRAINT fk_bookingitem_item 
    FOREIGN KEY (ITEM_NO) REFERENCES ITEM(ITEM_NO)
);

-- HOUSEKEEPING table
CREATE TABLE HOUSEKEEPING (
    HOUSEKEEP_ID VARCHAR2(20) PRIMARY KEY,
    HOMESTAY_ID VARCHAR2(20) NOT NULL,
    EMP_ID VARCHAR2(20) NOT NULL,
    HK_DATE DATE DEFAULT SYSDATE,
    STATUS VARCHAR2(20),
    CONSTRAINT fk_housekeeping_homestay 
    FOREIGN KEY (HOMESTAY_ID) REFERENCES HOMESTAY(HOMESTAY_ID),
    CONSTRAINT fk_housekeeping_employee 
    FOREIGN KEY (EMP_ID) REFERENCES EMPLOYEE(EMP_ID)
);

-- Add a check constraint for STATUS columns if needed
ALTER TABLE HOMESTAY ADD CONSTRAINT chk_homestay_status 
    CHECK (STATUS IN ('AVAILABLE', 'UNAVAILABLE'));

